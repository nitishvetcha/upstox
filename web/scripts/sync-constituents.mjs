import { assertCollectionAuthorized } from "./lib/collectionGuard.mjs";
assertCollectionAuthorized("sync-constituents.mjs", "external");

// Regenerates src/lib/services/breadthConstituents.generated.ts.
//   Membership: official NSE Indices constituent CSVs (niftyindices.com).
//   Instrument keys: current Upstox NSE instrument master (the same file the app uses for futures).
// Every constituent must resolve to an NSE_EQ / EQ row whose trading_symbol matches, or the script fails.
// Run: node scripts/sync-constituents.mjs
import { gunzipSync } from "node:zlib";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const UA = { "User-Agent": "Mozilla/5.0" };
const LISTS = {
  nifty: "ind_nifty50list.csv",
  banknifty: "ind_niftybanklist.csv",
  finnifty: "ind_niftyfinancelist.csv",
  midcpnifty: "ind_niftymidcapselect_list.csv",
};
// BSE blocks automated downloads. Save the official list from bseindia.com as one NSE symbol per line in
// scripts/constituents/<index>.txt; each symbol is still verified against the Upstox master.
const MANUAL = ["sensex", "bankex"];
const EXPECTED = { sensex: 30, bankex: 14 }; // hand-made lists only; NSE CSVs are authoritative

const masterRes = await fetch("https://assets.upstox.com/market-quote/instruments/exchange/NSE.json.gz");
if (!masterRes.ok) throw new Error(`instrument master HTTP ${masterRes.status}`);
const master = JSON.parse(gunzipSync(Buffer.from(await masterRes.arrayBuffer())).toString("utf8"));
const eq = master.filter((x) => x.segment === "NSE_EQ" && x.instrument_type === "EQ");
const byIsin = new Map(eq.map((x) => [x.isin ?? x.instrument_key.split("|")[1], x]));
const bySymbol = new Map(eq.map((x) => [x.trading_symbol, x]));

const out = {};
for (const [index, file] of Object.entries(LISTS)) {
  const res = await fetch(`https://niftyindices.com/IndexConstituent/${file}`, { headers: UA });
  if (!res.ok) throw new Error(`${file} HTTP ${res.status}`);
  const text = (await res.text()).trim();
  // A wrong file name returns HTTP 200 with an HTML page.
  if (!text.startsWith("Company Name,")) throw new Error(`${file}: not a constituent CSV`);
  const rows = text.split(/\r?\n/).slice(1).map((l) => {
    const p = l.split(",");
    return { name: p.slice(0, p.length - 4).join(",").trim(), symbol: p[p.length - 3].trim(), isin: p[p.length - 1].trim() };
  });
  out[index] = rows.map((r) => {
    const m = byIsin.get(r.isin) ?? bySymbol.get(r.symbol);
    if (!m) throw new Error(`${index}: ${r.symbol} (${r.isin}) not found in Upstox master`);
    if (m.trading_symbol !== r.symbol) throw new Error(`${index}: ${r.symbol} resolves to ${m.trading_symbol} in Upstox master`);
    return { symbol: r.symbol, name: r.name, isin: r.isin, instrumentKey: m.instrument_key };
  });
}
for (const index of MANUAL) {
  const file = new URL(`./constituents/${index}.txt`, import.meta.url);
  if (!existsSync(file)) { out[index] = []; console.warn(`${index}: no scripts/constituents/${index}.txt — breadth stays unavailable`); continue; }
  out[index] = readFileSync(file, "utf8").split(/\r?\n/).map((x) => x.trim().toUpperCase()).filter(Boolean).map((sym) => {
    const m = bySymbol.get(sym);
    if (!m) throw new Error(`${index}: ${sym} not found in Upstox NSE master`);
    return { symbol: sym, name: m.name, isin: m.isin ?? "", instrumentKey: m.instrument_key };
  });
}
for (const [index, list] of Object.entries(out)) {
  if (EXPECTED[index] && list.length && list.length !== EXPECTED[index]) throw new Error(`${index}: ${list.length} constituents, expected ${EXPECTED[index]}`);
}

const stamp = new Date().toISOString();
const ts = `// GENERATED by scripts/sync-constituents.mjs — do not edit by hand.
// Membership: NSE Indices constituent CSVs (${Object.values(LISTS).join(", ")}).
// Instrument keys: Upstox NSE instrument master. Each key verified (NSE_EQ, EQ, matching trading symbol).
// Generated: ${stamp}
export const GENERATED_AT = ${JSON.stringify(stamp)};
export const NIFTY_50 = ${JSON.stringify(out.nifty, null, 2)} as const;
export const BANK_NIFTY = ${JSON.stringify(out.banknifty, null, 2)} as const;
export const FIN_NIFTY = ${JSON.stringify(out.finnifty, null, 2)} as const;
export const MIDCAP_SELECT = ${JSON.stringify(out.midcpnifty, null, 2)} as const;
export const SENSEX = ${JSON.stringify(out.sensex, null, 2)} as { symbol: string; name: string; isin: string; instrumentKey: string }[];
export const BANKEX = ${JSON.stringify(out.bankex, null, 2)} as { symbol: string; name: string; isin: string; instrumentKey: string }[];
`;
writeFileSync(new URL("../src/lib/services/breadthConstituents.generated.ts", import.meta.url), ts);
console.log(`wrote ${Object.entries(out).map(([k, v]) => `${k} ${v.length}`).join(", ")} at ${stamp}`);
